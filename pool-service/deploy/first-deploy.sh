#!/usr/bin/env bash
# First deployment on the VPS: creates .env with fresh secrets, starts the stack,
# installs the nightly backup. Refuses to overwrite an existing .env.
# Usage (as claude, from anywhere): bash ~/autodidact/pool-service/deploy/first-deploy.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "${APP_DIR}"

[[ -f .env ]] && die ".env already exists. Use deploy/update.sh to redeploy, or deploy/set-password.sh to change the password."

if [[ "${SKIP_BUILD:-0}" != "1" ]]; then
  say "Building the app image (takes a few minutes the first time)"
  dc build api
fi

say "Generating secrets"
session_secret="$(openssl rand -hex 32)"
app_password="$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | cut -c1-16)"
password_hash="$(printf '%s' "${app_password}" | hash_password)"
[[ "${password_hash}" == '$argon2'* ]] || die "Password hashing failed"

umask 077
cat > .env <<ENV
# Generated by deploy/first-deploy.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep private.
ADMIN_PASSWORD_HASH='${password_hash}'
SESSION_SECRET=${session_secret}
LOG_LEVEL=info
ENV
chmod 600 .env
umask 022

say "Preparing data folders"
mkdir -p data/mongo data/photos backups
# The api container runs as the image's "node" user (uid 1000).
sudo chown 1000:1000 data/photos

say "Starting MongoDB and the API"
dc up -d
wait_healthy

say "Installing nightly backup (03:17 server time)"
if ! command -v crontab >/dev/null 2>&1; then
  sudo apt-get install -y cron
  sudo systemctl enable --now cron 2>/dev/null || true
fi
backup_line="17 3 * * * bash ${APP_DIR}/deploy/backup.sh >> ${APP_DIR}/backups/backup.log 2>&1"
( crontab -l 2>/dev/null | grep -v 'deploy/backup.sh' || true; echo "${backup_line}" ) | crontab -
crontab -l | grep backup.sh
bash "${APP_DIR}/deploy/backup.sh"

pw_file="${HOME}/pool-app-initial-password.txt"
( umask 077; printf '%s\n' "${app_password}" > "${pw_file}" )

cat <<MSG

============================================================
 Pool Service is running on http://127.0.0.1:3000
 Public URL (via Cloudflare Tunnel): https://poolapp.evolutiondfw.com

 App password: ${app_password}

 (Also saved in ${pw_file}, readable only by you.
  Change it any time:  bash ${APP_DIR}/deploy/set-password.sh
  then delete that file.)
============================================================
MSG
